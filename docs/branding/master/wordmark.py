# Caja de la palabra, MEDIDA sobre el entregable y comprobada por `bbox()` abajo.
# El alto es el total -desde el borde superior de la `p` hasta su descendente-, no
# la altura x: es lo que ocupa la palabra, que es lo que el lockup tiene que encajar.
WORD_W = 262.20469
WORD_H = 42.0

# Lo que el ojo lee como la linea de la palabra. No se usa para encuadrar -para eso
# esta WORD_H- pero sin ella no hay forma de hablar del tamano relativo del simbolo.
WORD_XH = 33.6


def paths():
    """Los ocho `d`, en orden de lectura."""
    return [d for _n, d in GLYPHS]


def glyph_names():
    """Que letra es cada path. Mismo papel que `build_marks.path_names()`."""
    return tuple(n for n, _d in GLYPHS)


_TOK = re.compile(r'([MLHVQZ])|(-?\d+\.?\d*(?:[eE]-?\d+)?)')


def _pts(d):
    """Puntos extremos reales del contorno: vertices y extremos de cada cuadratica.

    ⛔ No vale sacar min/max de los numeros del `d`. Dos razones, y las dos muerden
    en estos glifos: `H` y `V` llevan UNA coordenada -de ejes distintos-, asi que
    emparejar numeros de dos en dos mezcla x con y; y el punto de control de una
    cuadratica cae FUERA de la curva -a 1,082 r en estos arcos de 45 grados-, con
    lo que un min/max a pelo ensancha la caja un 8 % y la comprobacion de abajo
    dejaria pasar precisamente lo que existe para cazar.
    """
    out = []
    cur = (0.0, 0.0)
    nums = []
    cmd = None

    def emit_quad(c, e):
        # Extremo de una cuadratica en cada eje: t = (p0-c) / (p0 - 2c + p1).
        out.append(e)
        for i in (0, 1):
            den = cur[i] - 2 * c[i] + e[i]
            if abs(den) > 1e-12:
                t = (cur[i] - c[i]) / den
                if 0.0 < t < 1.0:
                    u = 1 - t
                    out.append(tuple(u * u * cur[j] + 2 * u * t * c[j] + t * t * e[j]
                                     for j in (0, 1)))

    def flush():
        nonlocal cur
        if cmd in ('M', 'L'):
            for i in range(0, len(nums), 2):
                cur = (nums[i], nums[i + 1])
                out.append(cur)
        elif cmd == 'H':
            for x in nums:
                cur = (x, cur[1])
                out.append(cur)
        elif cmd == 'V':
            for y in nums:
                cur = (cur[0], y)
                out.append(cur)
        elif cmd == 'Q':
            for i in range(0, len(nums), 4):
                c = (nums[i], nums[i + 1])
                e = (nums[i + 2], nums[i + 3])
                emit_quad(c, e)
                cur = e
        del nums[:]

    for m in _TOK.finditer(d):
        if m.group(1):
            flush()
            cmd = m.group(1)
        else:
            nums.append(float(m.group(2)))
    flush()
    return out


def bbox():
    """Caja real de la palabra, medida de los contornos."""
    pts = [p for d in paths() for p in _pts(d)]
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def check():
    """La caja declarada es la que dibujan los paths.

    ⛔ Existe porque `WORD_W` y `WORD_H` son lo UNICO de este fichero que esta a
    mano, y el lockup entero se encuadra con ellas: el ancho del lienzo del
    imagotipo es `2*PAD + marca + GAP + WORD_W`. Si alguien sustituye los glifos
    por una version retocada y la caja cambia, sin esto el imagotipo saldria
    descentrado en las seis superficies a la vez y nada fallaria al compilar.
    """
    x0, y0, x1, y1 = bbox()
    assert abs(x0) < 0.01 and abs(y0) < 0.01, \
        'la palabra no arranca en el origen: (%.4f, %.4f)' % (x0, y0)
    assert abs(x1 - WORD_W) < 0.01, 'WORD_W dice %g, los paths miden %.5f' % (WORD_W, x1)
    assert abs(y1 - WORD_H) < 0.01, 'WORD_H dice %g, los paths miden %.5f' % (WORD_H, y1)
    assert len(GLYPHS) == 8, 'se esperaban 8 glifos, hay %d' % len(GLYPHS)
    assert ''.join(glyph_names()) == 'paparcar', \
        'los glifos deletrean %r' % ''.join(glyph_names())


