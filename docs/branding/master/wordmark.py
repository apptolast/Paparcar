def build():
    """La palabra sola, como SVG. `export_surfaces.py` compara su salida con el fichero."""
    L = ['<svg xmlns="http://www.w3.org/2000/svg" width="%g" height="%g" '
         'viewBox="0 0 %g %g" fill="#0D1117">' % (WORD_W, WORD_H, WORD_W, WORD_H),
         '  <!--', NOTE.rstrip(), '-->']
    for name, d in GLYPHS:
        L.append('  <!-- %s -->' % name)
        L.append('  <path d="%s"/>' % d)
    L.append('</svg>')
    return chr(10).join(L) + chr(10)


