package com.rndeveloper.paparcar.architecture

import org.junit.Test
import java.io.File
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.test.fail

/**
 * What we paste into the Play Console must BE the copy this repo calls current.
 * [PLAY-A-LISTING-MUST-MATCH-THE-BUILD-IN-PRODUCTION-001]
 *
 * The listing copy lived in two places — `LISTING-v1.3.0.md`, which is reviewed and reasoned about,
 * and `paste/play-<locale>.txt`, which is what a human actually copies into the Console — and
 * nothing compared them. So they drifted, in the direction that costs money: for 29 days the
 * pastable files still promised *"all your cars in one garage"*, a promise `MONEY-001` had already
 * made false ([com.rndeveloper.paparcar.domain.entitlement.FREE_OWN_VEHICLE_LIMIT] is 1), and they
 * were missing the 25-09 correction to step 1 of HOW IT WORKS. The first defect never reached
 * production by luck — whoever pasted, pasted from the `.md`. Luck is not a guard.
 *
 * `paste/` is now GENERATED by `docs/release/play-listing/tools/make_paste.py`. This class is the
 * witness that it was regenerated: it re-reads the source of truth and checks that every field of
 * every locale matches what is committed.
 *
 * ## Why it parses instead of rendering
 *
 * The tool renders; this test only PARSES and compares field by field. Re-implementing the
 * rendering in Kotlin would put the same format in two languages, which is the very shape of bug
 * this file exists to catch. Byte-for-byte equality is the tool's own `--check`; the invariant that
 * matters here — *the name, the short description and the full description that get pasted are the
 * ones the `.md` declares* — survives any change to the file's decoration.
 *
 * ## What it deliberately does not do
 *
 * It cannot tell whether the copy is TRUE of the build in production. A listing describing features
 * that shipped after the published `versionCode` is a real defect and no test can see it; that
 * belongs to the release checklist in `docs/release/play-listing/README.md`.
 *
 * ⛔ Reads files, touches no bytecode, so Gradle calls it UP-TO-DATE and never runs it. Falsifying
 * it needs `--rerun-tasks`, like every guard in this package.
 */
class PlayListingPasteParityGuardrailTest {

    @Test
    fun `should paste exactly the copy the listing source declares for every locale`() {
        val source = read(LISTING_SOURCE)
        val names = table(source, "app-name")
        val shorts = table(source, "short-description")
        val fulls = fullDescriptions(source)

        assertEquals(LOCALES.toSet(), names.keys, "app names in $LISTING_SOURCE")
        assertEquals(LOCALES.toSet(), shorts.keys, "short descriptions in $LISTING_SOURCE")
        assertEquals(LOCALES.toSet(), fulls.keys, "full descriptions in $LISTING_SOURCE")

        for (locale in LOCALES) {
            val relative = "$PASTE_DIR/play-$locale.txt"
            val pasted = read(relative)

            assertTrue(
                pasted.contains(GENERATED_MARKER),
                "$relative lost its generated banner — it was hand-edited, which is how the copy " +
                    "drifted in the first place. Regenerate with: $REGENERATE",
            )

            assertEquals(names.getValue(locale), pasted.field(1, relative), "app name in $relative")
            assertEquals(shorts.getValue(locale), pasted.field(2, relative), "short description in $relative")
            assertEquals(fulls.getValue(locale), pasted.field(3, relative), "full description in $relative")
        }
    }

    @Test
    fun `should carry every locale in the single-file import too`() {
        val fulls = fullDescriptions(read(LISTING_SOURCE))
        val relative = "$PASTE_DIR/play-listing-import.md"
        val importAll = read(relative)

        assertTrue(importAll.contains(GENERATED_MARKER), "$relative lost its generated banner")
        for (locale in LOCALES) {
            assertTrue(
                importAll.contains("## Locale: $locale"),
                "$relative has no block for $locale. Regenerate with: $REGENERATE",
            )
            assertTrue(
                importAll.contains(fulls.getValue(locale)),
                "the $locale full description in $relative is not the one $LISTING_SOURCE declares. " +
                    "Regenerate with: $REGENERATE",
            )
        }
    }

    /**
     * The floors. A parser that silently matches nothing turns this whole class green, which is the
     * failure mode a guard has to rule out before it can claim anything.
     */
    @Test
    fun `should prove the parser actually read the listing`() {
        val fulls = fullDescriptions(read(LISTING_SOURCE))

        assertEquals(LOCALE_COUNT, fulls.size, "locales parsed out of $LISTING_SOURCE")
        for ((locale, text) in fulls) {
            assertTrue(
                text.length in FULL_DESCRIPTION_FLOOR..PLAY_FULL_DESCRIPTION_MAX,
                "the $locale full description parsed to ${text.length} chars, outside " +
                    "$FULL_DESCRIPTION_FLOOR..$PLAY_FULL_DESCRIPTION_MAX — either the parse broke or " +
                    "Play will reject it",
            )
        }
    }

    /** The text of numbered field [index] of a `paste/play-<locale>.txt`, between its rulers. */
    private fun String.field(index: Int, relative: String): String {
        val opening = Regex("^--- $index\\. [^-]+ ---$", RegexOption.MULTILINE).find(this)
            ?: fail("$relative has no field $index — regenerate with: $REGENERATE")
        val rest = substring(opening.range.last + 1)
        val next = Regex("^--- \\d+\\. ", RegexOption.MULTILINE).find(rest)
        return (if (next == null) rest else rest.substring(0, next.range.first)).trim('\n')
    }

    /**
     * The slice a `<!-- paste-source: MARKER -->` introduces, ending at the NEXT marker.
     *
     * ⛔ Not at the next level-2 heading: the discarded short-description variant is a `### ` inside
     * the same section, so cutting there swallowed it and — being last — it WON. That is how the
     * generator's first run wrote the very 29-08 text this ticket was removing.
     */
    private fun section(md: String, marker: String): String {
        val start = md.indexOf("<!-- paste-source: $marker -->")
        if (start < 0) fail("$LISTING_SOURCE has no '<!-- paste-source: $marker -->' marker")
        val rest = md.substring(start)
        val stop = listOfNotNull(
            rest.indexOf("\n<!-- paste-source:", 1).takeIf { it > 0 },
            rest.indexOf("\n## ", 1).takeIf { it > 0 },
        ).minOrNull()
        return if (stop == null) rest else rest.substring(0, stop)
    }

    /** Locale to text, from the table rows a marker introduces: pipe, locale, pipe, backticked text. */
    private fun table(md: String, marker: String): Map<String, String> =
        Regex("""^\|\s*([a-z]{2}-[A-Z]{2})\s*\|\s*`(.+?)`\s*\|""", RegexOption.MULTILINE)
            .findAll(section(md, marker))
            .associate { it.groupValues[1] to it.groupValues[2] }

    /** Locale to text, from the fenced blocks under the full-description heading. */
    private fun fullDescriptions(md: String): Map<String, String> {
        val heading = md.indexOf(FULL_DESCRIPTION_HEADING)
        if (heading < 0) fail("$LISTING_SOURCE has no '$FULL_DESCRIPTION_HEADING' heading")
        return Regex(
            """^### ([a-z]{2}-[A-Z]{2})\s*\n+```\n(.*?)\n```""",
            setOf(RegexOption.MULTILINE, RegexOption.DOT_MATCHES_ALL),
        )
            .findAll(md.substring(heading))
            .associate { it.groupValues[1] to it.groupValues[2] }
    }

    private fun read(relative: String): String =
        File(repoRoot, relative).takeIf { it.isFile }?.readText()
            ?: fail("not found from ${repoRoot.path}: $relative")

    private companion object {
        const val LISTING_DIR = "docs/release/play-listing"
        const val LISTING_SOURCE = "$LISTING_DIR/LISTING-v1.3.0.md"
        const val PASTE_DIR = "$LISTING_DIR/paste"
        const val REGENERATE = "python $LISTING_DIR/tools/make_paste.py"

        const val GENERATED_MARKER = "GENERADO por tools/make_paste.py"
        const val FULL_DESCRIPTION_HEADING = "## Descripción completa"

        /** The nine the app ships, in the order the generator writes them. */
        val LOCALES = listOf("en-US", "es-ES", "it-IT", "pt-PT", "fr-FR", "de-DE", "nl-NL", "pl-PL", "ro-RO")
        const val LOCALE_COUNT = 9

        /** Play's own ceiling, and a floor at under a third of it: measured at ~3.700 chars on 27-09. */
        const val PLAY_FULL_DESCRIPTION_MAX = 4000
        const val FULL_DESCRIPTION_FLOOR = 1200

        val repoRoot: File = generateSequence(File("").absoluteFile) { it.parentFile }
            .firstOrNull { File(it, "settings.gradle.kts").isFile }
            ?: error("repo root not found from ${File("").absolutePath}")
    }
}
